import 'package:d_rocket_builder/src/rest/parser.dart';

/// Emite el código Dart para una [ParsedClient].
///
/// Movido desde `d_rest_build/lib/emitter.dart` ( del roadmap
/// de d_rocket). El codegen ahora produce código que importa de
/// `package:d_rocket/d_rocket.dart` (que reexporta `RestRequest`,
/// `dRest`, `invokeRequest`, `@RestClient` originales de `d_rest`).
String emitClient(ParsedClient client) {
  final StringBuffer buffer = StringBuffer();
  buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
  buffer.writeln('// Generated by d_rocket_builder:rest_client.');
  buffer.writeln('// Source: ${client.className}');
  buffer.writeln();
  buffer.writeln('// ignore_for_file: type=lint, prefer_single_quotes');
  buffer.writeln();
  // NOTE: do NOT emit `part of '...';` here.
  // The builder is wired with `PartBuilder` in
  // `build.yaml` (d_rocket_builder:rest_client),
  // which automatically prepends the
  // `part of '<source>.dart';` directive.
  // Emitting it manually would produce a
  // double `part of` and Dart would refuse to
  // compile with: "Only one part-of directive
  // may be declared in a file."

  // === Concrete class ===
  buffer
      .writeln('class _\$${client.className} implements ${client.className} {');
  buffer.writeln('  _\$${client.className}({RestClientConfig? config})');
  buffer.writeln('      : _client = config?.build(dRest.client),');
  buffer.writeln(
    "        _baseUrl = config?.baseUrl ?? ${_quoteString(client.baseUrl)};",
  );
  buffer.writeln('  final HttpClient? _client;');
  buffer.writeln('  final String _baseUrl;');
  buffer.writeln();
  buffer.writeln('  /// Crea una instancia del cliente tipado.');
  buffer.writeln(
      '  static ${client.className} create({RestClientConfig? config}) =>');
  buffer.writeln('      _\$${client.className}(config: config);');
  buffer.writeln();

  for (final ParsedMethod method in client.methods) {
    _emitMethod(buffer, client, method);
  }

  buffer.writeln('}');

  buffer.writeln();
  buffer.writeln(
      '${client.className} create${client.className}({RestClientConfig? config}) =>');
  buffer.writeln('    _\$${client.className}.create(config: config);');

  // The central `d_rocket_registry.g.dart` emits
  // `register<ClassName>RestClient()` for every
  // `@RestClient` class it discovers (see
  // `record_registry_builder.dart`). That function
  // must exist in THIS part file (it's the part
  // that "owns" the class), so the registry's call
  // resolves. We emit it here, returning the
  // factory `create()`.
  buffer.writeln();
  buffer.writeln(
      '${client.className} register${client.className}RestClient() =>');
  buffer.writeln('    _\$${client.className}.create();');

  return buffer.toString();
}

void _emitMethod(
    StringBuffer buffer, ParsedClient client, ParsedMethod method) {
  final String returnTypeStr = _methodReturnTypeString(method);
  final String fullPath = '${client.classPath}${method.path}';

  buffer.writeln('  @override');
  buffer.writeln(
    '  $returnTypeStr ${method.name}(${_parameterList(method)})'
    '${method.returnType.isStream ? '' : ' async'} {',
  );

  // Build headers literal
  buffer.writeln('    final Map<String, String> _headers = <String, String>{');
  for (final MapEntry<String, String> e in client.classHeaders.entries) {
    buffer.writeln("      '${_escape(e.key)}': '${_escape(e.value)}',");
  }
  for (final MapEntry<String, String> e in method.methodHeaders.entries) {
    buffer.writeln("      '${_escape(e.key)}': '${_escape(e.value)}',");
  }
  buffer.writeln('    };');

  // Header params (from @Header)
  final List<ParsedParameter> headerParams = method.parameters
      .where((ParsedParameter p) => p.kind == ParamKind.header)
      .toList();
  if (headerParams.isNotEmpty) {
    buffer.writeln('    _headers.addAll(<String, String>{');
    for (final ParsedParameter p in headerParams) {
      final String key = p.annotationName ?? p.name;
      if (p.isEnum) {
        buffer.writeln(
          "      '${_escape(key)}': '\${${_enumValueExpression(p)}}',",
        );
      } else {
        buffer.writeln("      '${_escape(key)}': '\$${p.name}'.toString(),");
      }
    }
    buffer.writeln('    });');
  }

  // Path params
  final List<ParsedParameter> pathParams = method.parameters
      .where((ParsedParameter p) => p.kind == ParamKind.path)
      .toList();
  String pathParamsValue = 'const <String, Object>{}';
  if (pathParams.isNotEmpty) {
    buffer.writeln(
        '    final Map<String, Object> _pathParams = <String, Object>{');
    for (final ParsedParameter p in pathParams) {
      final String key = p.annotationName ?? p.name;
      buffer.writeln(
        "      '$key': ${p.isEnum ? _enumValueExpression(p) : '${p.name} as Object'},",
      );
    }
    buffer.writeln('    };');
    pathParamsValue = '_pathParams';
  }

  // Query params
  final List<ParsedParameter> queryParams = method.parameters
      .where((ParsedParameter p) => p.kind == ParamKind.query)
      .toList();
  String queryParamsValue = 'const <String, String>{}';
  if (queryParams.isNotEmpty) {
    buffer.writeln('    final Map<String, String> _query = <String, String>{');
    for (final ParsedParameter p in queryParams) {
      final String key = p.annotationName ?? p.name;
      buffer.writeln(
        "      '$key': ${p.isEnum ? _enumValueExpression(p) : '${p.name}.toString()'},",
      );
    }
    buffer.writeln('    };');
    queryParamsValue = '_query';
  }

  // Body
  final List<ParsedParameter> bodyParams = method.parameters
      .where((ParsedParameter p) =>
          p.kind == ParamKind.body || p.kind == ParamKind.rawBody)
      .toList();
  String bodyExpr = 'null';
  if (bodyParams.isNotEmpty) {
    final ParsedParameter p = bodyParams.first;
    if (p.kind == ParamKind.rawBody) {
      bodyExpr = '${p.name}';
    } else {
      bodyExpr = 'dRest.encodeBody<${p.dartType}>(${p.name})';
    }
  }

  final List<ParsedParameter> partParams = method.parameters
      .where((ParsedParameter p) => p.kind == ParamKind.part)
      .toList();
  if (partParams.isNotEmpty) {
    buffer
        .writeln('    final RestMultipartBody _multipart = RestMultipartBody(');
    buffer.writeln('      parts: <RestMultipartPart>[');
    for (final ParsedParameter p in partParams) {
      final String key = p.annotationName ?? p.name;
      buffer.writeln(
          "        RestMultipartPart.fromValue('${_escape(key)}', ${p.name}),");
    }
    buffer.writeln('      ],');
    buffer.writeln('    );');
    buffer.writeln("    _headers['Content-Type'] = _multipart.contentType;");
    bodyExpr = '_multipart.toBytes()';
  }

  // Build the request
  buffer.writeln('    final RestRequest _request = RestRequest(');
  buffer.writeln("      method: '${method.verb}',");
  buffer.writeln("      path: ${_quoteString(fullPath)},");
  buffer.writeln('      baseUrl: _baseUrl,');
  buffer.writeln('      headers: _headers,');
  if (bodyParams.isNotEmpty || partParams.isNotEmpty) {
    buffer.writeln('      body: $bodyExpr,');
  }
  if (queryParams.isNotEmpty) {
    buffer.writeln('      queryParameters: $queryParamsValue,');
  }
  if (pathParams.isNotEmpty) {
    buffer.writeln('      pathParameters: $pathParamsValue,');
  }
  if (client.classTimeout != null) {
    buffer.writeln('      timeout: ${_durationLiteral(client.classTimeout!)},');
  }
  buffer.writeln('    );');

  if (method.returnType.isStream && method.queryCacheTags.isNotEmpty) {
    final String inner = method.returnType.innerType ?? 'dynamic';
    buffer.writeln('    return dRest.queryCache.watch<$inner>(');
    buffer.writeln("      key: '\${_request.method} \${_request.fullUrl}',");
    buffer.writeln('      tags: <String>[');
    for (final String tag in method.queryCacheTags) {
      buffer.writeln('        resolveRestQueryTemplate(');
      buffer.writeln("          '${_escape(tag)}',");
      buffer.writeln('          <String, Object?>{');
      _emitTagValues(buffer, method, tag);
      buffer.writeln('          },');
      buffer.writeln('        ),');
    }
    buffer.writeln('      ],');
    buffer.writeln(
        '      staleTime: ${_durationLiteral(method.queryCacheStaleTime ?? const Duration(seconds: 30))},');
    buffer.writeln(
        '      cacheTime: ${_durationLiteral(method.queryCacheTime ?? const Duration(minutes: 5))},');
    buffer.writeln('      loader: () => invokeRequest<$inner>(');
    buffer.writeln('        _request,');
    buffer.writeln('        (dynamic data) => dRest.decodeBody<$inner>(data),');
    buffer.writeln('        client: _client,');
    buffer.writeln('      ),');
    buffer.writeln('    );');
  } else if (method.returnType.isVoid) {
    buffer.writeln('    await invokeRequest<void>(');
    buffer.writeln('      _request,');
    buffer.writeln('      (dynamic data) => null,');
    buffer.writeln('      client: _client,');
    buffer.writeln('    );');
    _emitInvalidation(buffer, method);
  } else if (method.returnType.isDynamic) {
    if (method.invalidationTags.isNotEmpty) {
      buffer
          .writeln('    final dynamic _result = await invokeRequest<dynamic>(');
    } else {
      buffer.writeln('    return invokeRequest<dynamic>(');
    }
    buffer.writeln('      _request,');
    buffer.writeln('      (dynamic data) => data,');
    buffer.writeln('      client: _client,');
    buffer.writeln('    );');
    if (method.invalidationTags.isNotEmpty) {
      _emitInvalidation(buffer, method);
      buffer.writeln('    return _result;');
    }
  } else {
    final String t = method.returnType.dartType;
    final String decoderType =
        t.endsWith('?') ? t.substring(0, t.length - 1) : t;
    if (method.invalidationTags.isNotEmpty) {
      buffer.writeln('    final $t _result = await invokeRequest<$t>(');
    } else {
      buffer.writeln('    return invokeRequest<$t>(');
    }
    buffer.writeln('      _request,');
    if (method.returnType.isPage) {
      final String inner = method.returnType.innerType ?? 'dynamic';
      buffer.writeln('      (dynamic data) => RestPage<$inner>.fromJson(');
      buffer.writeln('        data as Map<String, dynamic>,');
      buffer
          .writeln('        (Object? item) => dRest.decodeBody<$inner>(item),');
      buffer.writeln('      ),');
    } else {
      buffer.writeln(
          '      (dynamic data) => dRest.decodeBody<$decoderType>(data),');
    }
    buffer.writeln('      client: _client,');
    buffer.writeln('    );');
    if (method.invalidationTags.isNotEmpty) {
      _emitInvalidation(buffer, method);
      buffer.writeln('    return _result;');
    }
  }

  buffer.writeln('  }');
  buffer.writeln();
}

String _enumValueExpression(ParsedParameter parameter) => parameter.isNullable
    ? '${parameter.name}?.name.toString()'
    : '${parameter.name}.name';

String _methodReturnTypeString(ParsedMethod method) {
  if (method.returnType.isVoid) return 'Future<void>';
  if (method.returnType.isStream) {
    return 'Stream<${method.returnType.innerType ?? 'dynamic'}>';
  }
  if (method.returnType.isList) {
    final String inner = method.returnType.innerType ?? 'dynamic';
    return 'Future<List<$inner>>';
  }
  if (method.returnType.isMap) {
    return 'Future<${method.returnType.dartType}>';
  }
  return 'Future<${method.returnType.dartType}>';
}

void _emitInvalidation(StringBuffer buffer, ParsedMethod method) {
  if (method.invalidationTags.isEmpty) return;
  buffer.writeln('    await dRest.queryCache.invalidate(<String>[');
  for (final String tag in method.invalidationTags) {
    buffer.writeln('      resolveRestQueryTemplate(');
    buffer.writeln("        '${_escape(tag)}',");
    buffer.writeln('        <String, Object?>{');
    _emitTagValues(buffer, method, tag);
    buffer.writeln('        },');
    buffer.writeln('      ),');
  }
  buffer.writeln('    ]);');
}

void _emitTagValues(
  StringBuffer buffer,
  ParsedMethod method,
  String tag,
) {
  final RegExp tokenPattern = RegExp(r'\{([a-zA-Z_]\w*(?:\.[a-zA-Z_]\w*)?)\}');
  final Set<String> tokens = tokenPattern
      .allMatches(tag)
      .map((RegExpMatch match) => match.group(1)!)
      .toSet();
  for (final String token in tokens) {
    final String root = token.split('.').first;
    final ParsedParameter? parameter = method.parameters
        .where((ParsedParameter p) => p.name == root)
        .cast<ParsedParameter?>()
        .firstWhere((ParsedParameter? p) => p != null, orElse: () => null);
    if (parameter == null) continue;
    final String expression = token.contains('.')
        ? '${parameter.name}.${token.substring(root.length + 1)}'
        : parameter.name;
    buffer.writeln("            '$token': $expression,");
  }
}

String _parameterList(ParsedMethod method) {
  final List<String> parts = <String>[];
  for (final ParsedParameter p in method.parameters) {
    final String required = (p.isRequired && p.isNamed) ? 'required ' : '';
    parts.add('$required${p.dartType} ${p.name}');
  }
  return parts.join(', ');
}

String _quoteString(String value) {
  return "'${value.replaceAll(r'\', r'\\\\').replaceAll("'", r"\'")}'";
}

String _escape(String value) {
  return value.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
}

String _durationLiteral(Duration d) {
  return 'Duration(microseconds: ${d.inMicroseconds})';
}
